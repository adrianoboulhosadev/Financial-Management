const { withAppBuildGradle } = require('expo/config-plugins')

/**
 * The gradle property that decides whether a real keystore is in play. When it
 * is absent the build falls back to the debug signing config, which is what
 * keeps `assembleRelease` working on a machine that has not generated a
 * keystore yet.
 */
const STORE_FILE = 'FINANCIAL_RELEASE_STORE_FILE'

/** Anchors in the template Expo generates. Matched exactly so that an upstream
 * change is caught here (loudly) instead of silently producing an APK still
 * signed with the debug key. */
const DEBUG_CONFIG_END = `            keyPassword 'android'
        }
    }`
const RELEASE_SIGNING = `            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`

const RELEASE_CONFIG = `            keyPassword 'android'
        }
        release {
            // Filled from the BUILDING MACHINE's ~/.gradle/gradle.properties, so
            // the keystore path and its passwords never enter the repository.
            if (project.hasProperty('${STORE_FILE}')) {
                storeFile file(${STORE_FILE})
                storePassword FINANCIAL_RELEASE_STORE_PASSWORD
                keyAlias FINANCIAL_RELEASE_KEY_ALIAS
                keyPassword FINANCIAL_RELEASE_KEY_PASSWORD
            }
        }
    }`

const CONDITIONAL_SIGNING = `            // Real keystore when the machine has one, debug key otherwise — an
            // APK that installs is worth more than a build that refuses to run
            // before anybody has generated a key.
            signingConfig project.hasProperty('${STORE_FILE}') ? signingConfigs.release : signingConfigs.debug`

/**
 * Points the RELEASE build at a proper keystore.
 *
 * It is a config plugin and not a hand edit of `android/app/build.gradle`
 * because that folder is BUILD OUTPUT: it is regenerated by every
 * `expo prebuild`, so an edit made there survives exactly until the next one.
 *
 * Expo's own template signs release with the DEBUG key and says so in a comment
 * ("Caution! In production, you need to generate your own keystore file"). That
 * is fine until the debug key changes — then Android refuses to update the
 * installed app, because the signature no longer matches, and the only way out
 * is uninstalling and losing the app's stored session.
 */
const withReleaseSigning = (config) =>
  withAppBuildGradle(config, (gradle) => {
    let contents = gradle.modResults.contents

    for (const [anchor, replacement] of [
      [DEBUG_CONFIG_END, RELEASE_CONFIG],
      [RELEASE_SIGNING, CONDITIONAL_SIGNING],
    ]) {
      if (!contents.includes(anchor)) {
        throw new Error(
          'with-release-signing: the expected block is no longer in the generated ' +
            'build.gradle. Expo changed its template — update this plugin, and do not ' +
            `ship a release signed with the debug key.\n\nMissing:\n${anchor}`,
        )
      }
      contents = contents.replace(anchor, replacement)
    }

    gradle.modResults.contents = contents
    return gradle
  })

module.exports = withReleaseSigning
